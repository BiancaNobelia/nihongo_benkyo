export function memoryFor(card) {
  const examples=kanjiExamples(card);
  const example=examples.find(e=>e.word.includes(card.char)) || examples[0];
  const parts=KANJI_COMPONENTS[card.char] || [];
  const story=MEMORY_STORIES[card.char];
  const anchors=MEMORY_ANCHORS[card.char] || [];
  const meaning=card.meaning.split(';')[0].trim().toLocaleLowerCase('id');
  return {
    method:story?'Cerita bentuk':parts.length?'Pecah bentuk':anchors.length?'Jangkar bentuk':'Kaitkan dengan kata',
    text:story || (parts.length
      ? `Untuk mengingat ${card.char} (${meaning}), pecah bentuknya menjadi ${parts.map(p=>`${p.symbol} (${p.meaning.toLocaleLowerCase('id')})${p.position?' '+p.position:''}`).join(' + ')}. Tulis satu kelompok bentuk setiap kali, lalu satukan sambil menyebut artinya.`
      : anchors.length
        ? `Jadikan ${anchors.map(p=>`${p.symbol} (${p.meaning.toLocaleLowerCase('id')})`).join(' dan ')} sebagai jangkar saat mengingat ${card.char}: “${meaning}”. Kenali bagian itu dahulu, lalu salin goresan di sekitarnya. Tutup contoh dan coba tulis ulang. Bagian yang disebut ini bukan seluruh penyusun kanji.`
        : `Pasangkan bentuk ${card.char} dengan arti “${meaning}”. Amati siluetnya dan ${card.strokes} goresannya, lalu gunakan kata di bawah sebagai pengait bunyi. Tutup contoh, tulis kembali ${card.char} dari ingatan, kemudian bandingkan bentuknya.`),
    example,
  };
}
