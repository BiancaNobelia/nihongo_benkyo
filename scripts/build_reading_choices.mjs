// Build from committed word-reading exclusions and the pinned KANJIDIC catalog.
// No network or generated sentences. Ambiguous/irregular segmentation is skipped.
import {readFileSync, writeFileSync} from 'node:fs';
import {KANJI} from '../kanji-data.js';
import {PRACTICE_BANKS} from '../practice-banks.js';
import {readingQuestionKey} from '../reading-history.js';

const root=new URL('../',import.meta.url);
const source=JSON.parse(readFileSync(new URL('data/reading-choice-source.json',root)));
const acceptedByWord=new Map(source.words.map(q=>[q.word,q.readings]));
const kanji=new Map(KANJI.map(k=>[k.char,k]));
const hiragana=text=>text.replace(/[ァ-ヶ]/gu,c=>String.fromCodePoint(c.codePointAt(0)-0x60));
const readings=char=>{
  const k=kanji.get(char);
  return k ? ['on','kun'].flatMap(type=>k[type].map(sourceReading=>({
    type,sourceReading,stem:hiragana(sourceReading.replace(/-/g,'').split('.')[0]),
  }))).filter(r=>/^[ぁ-ゖ]+$/u.test(r.stem)) : [];
};

function segments(word,answer) {
  const chars=[...word], found=[];
  function visit(index,offset,parts) {
    if(found.length>1)return;
    if(index===chars.length){if(offset===answer.length)found.push(parts);return;}
    const char=chars[index];
    const stems=kanji.has(char) ? [...new Set(readings(char).map(r=>r.stem))] : [hiragana(char)];
    for(const stem of stems)if(answer.startsWith(stem,offset))visit(index+1,offset+stem.length,[...parts,{char,stem,offset}]);
  }
  visit(0,0,[]);
  return found.length===1 ? found[0] : [];
}

function alternateReadings(q,accepted) {
  if(q.readingCategory==='special')return [];
  const candidates=[];
  for(const part of segments(q.word,q.reading)){
    for(const other of readings(part.char)){
      if(other.stem===part.stem)continue;
      // Do not paste the stem of a different inflected kun reading onto an
      // unrelated ending (e.g. ま.ず must not produce ましゅう for 先週).
      const okurigana=other.sourceReading.split('.')[1];
      if(okurigana && !q.word.slice(q.word.indexOf(part.char)+part.char.length).startsWith(okurigana))continue;
      const value=q.reading.slice(0,part.offset)+other.stem+q.reading.slice(part.offset+part.stem.length);
      if(accepted.has(value) || value.length>q.reading.length+3 || candidates.some(c=>c.value===value))continue;
      candidates.push({value,char:part.char,from:part.stem,to:other.stem,type:other.type,sourceReading:other.sourceReading});
    }
  }
  return candidates;
}

function phoneticChoices(q,accepted) {
  const choices=q.distractors.filter(value=>!accepted.has(value));
  const suffix=q.word.match(/[ぁ-ゖ]+$/u)?.[0] || '';
  const stem=suffix && q.reading.endsWith(suffix) ? q.reading.slice(0,-suffix.length) : q.reading;
  const ending=q.reading.slice(stem.length);
  for(let i=0;i<stem.length;i++)for(const group of ['かが','きぎ','くぐ','けげ','こご','さざ','しじ','すず','せぜ','そぞ','ただ','ちぢ','つづ','てで','とど','はばぱ','ひびぴ','ふぶぷ','へべぺ','ほぼぽ','ゃや','ゅゆ','ょよ','っつ','あいうえお','かきくけこ','さしすせそ','たちつてと','なにぬねの','はひふへほ','まみむめも','らりるれろ']){
    if(!group.includes(stem[i]))continue;
    for(const kana of group){
      const value=stem.slice(0,i)+kana+stem.slice(i+1)+ending;
      if(!accepted.has(value) && !/^[っゃゅょ]/u.test(value) && !choices.includes(value))choices.push(value);
    }
  }
  if(choices.length<3)throw Error(`Not enough safe choices for ${q.word}`);
  // Retain the authored choices wherever they are safe, with fallbacks when a
  // dictionary alternate has been excluded or overlaps an on/kun distractor.
  return choices.slice(0,8);
}

const rows=PRACTICE_BANKS['jlpt-reading'].map(q=>{
  const sourceReadings=acceptedByWord.get(q.word);
  if(q.readingCategory!=='special' && !sourceReadings)throw Error(`Missing source: ${q.word}`);
  // Counters/dates have authored context-specific accepted readings. In
  // particular, ついたち and いちにち are not interchangeable in the sentences.
  const accepted=new Set([q.reading,...(q.readingCategory==='special' ? q.acceptedReadings || [] : sourceReadings)].map(hiragana));
  if(q.readingCategory!=='special'){
    const characters=[...q.word].filter(c=>kanji.has(c));
    if(characters.length===1){
      const char=characters[0], [prefix,suffix]=q.word.split(char);
      for(const r of readings(char)){
        // A bare character can legitimately be read with several on/kun
        // readings. Also exclude exact kun+okurigana forms even when a rare
        // reading is absent from the word dictionary (e.g. 帰る・おくる).
        if(!prefix && !suffix)accepted.add(r.stem);
        if(r.type==='kun' && r.sourceReading.split('.')[1]===suffix)accepted.add(prefix+r.stem+suffix);
      }
    }
  }
  return {key:readingQuestionKey(q),accepted:[...accepted],alternatives:alternateReadings(q,accepted),phonetic:phoneticChoices(q,accepted)};
});
writeFileSync(new URL('reading-choice-data.js',root),
  '// Generated by scripts/build_reading_choices.mjs. KANJIDIC2 / JMdict, CC BY-SA 4.0; see DATA-SOURCES.md.\n'+
  'export const READING_CHOICES = [\n'+rows.map(row=>'  '+JSON.stringify(row)).join(',\n')+'\n];\n');
