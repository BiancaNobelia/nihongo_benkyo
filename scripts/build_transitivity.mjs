import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {TRANSITIVITY_SOURCE,TRANSITIVITY_REFERENCE_NOTE} from '../data/transitivity-source.mjs';

function annotated(raw) {
  let sentence='',cursor=0;const furigana=[];
  for(const m of raw.matchAll(/\[([^\[\]|]+)\|([^\[\]|]+)\]/gu)) {
    sentence+=raw.slice(cursor,m.index);furigana.push([sentence.length,m[1],m[2]]);sentence+=m[1];cursor=m.index+m[0].length;
  }
  sentence+=raw.slice(cursor);assert.ok(!/[\[\]|]/u.test(sentence));
  for(let i=0;i<sentence.length;i++)if(/[\p{Script=Han}々]/u.test(sentence[i]))assert.ok(furigana.some(([n,w])=>i>=n&&i<n+w.length),`Missing reading: ${sentence}`);
  for(const [,w,r] of furigana)assert.match(r,/^[ぁ-ゖー]+$/u,w);
  return {sentence,furigana};
}
const pairs=TRANSITIVITY_SOURCE.map(({jExamples,tExamples,...p})=>p);
const entries=TRANSITIVITY_SOURCE.flatMap(p=>['ji','ta'].flatMap(kind=>p[kind==='ji'?'jExamples':'tExamples'].map(([translation,raw,reason],i)=>{
  assert.ok(translation&&reason);return {id:`transitivity-${p.id}-${kind}-${i+1}`,pairId:p.id,kind,translation,...annotated(raw),reason};
})));
assert.equal(new Set(pairs.map(p=>p.id)).size,pairs.length);
assert.equal(new Set(entries.map(q=>q.id)).size,entries.length);
assert.equal(new Set(entries.map(q=>q.translation)).size,entries.length);
for(const p of pairs){assert.notEqual(p.ji.masu,p.ta.masu);for(const k of ['ji','ta']){const v=p[k];for(const key of ['word','reading','masu','masuReading','te','meaning'])assert.ok(v[key]);assert.match(v.masuReading,/^[ぁ-ゖ]+ます$/u);assert.match(v.reading,/^[ぁ-ゖ]+$/u);}}
writeFileSync(new URL('../transitivity-data.js',import.meta.url),'// Generated by scripts/build_transitivity.mjs; sources: DATA-SOURCES.md.\nexport const TRANSITIVITY_PAIRS = '+JSON.stringify(pairs,null,2)+';\nexport const TRANSITIVITY_ENTRIES = [\n'+entries.map(q=>'  '+JSON.stringify(q)).join(',\n')+'\n];\nexport const TRANSITIVITY_REFERENCE_NOTE = '+JSON.stringify(TRANSITIVITY_REFERENCE_NOTE)+';\n');
console.log(`${pairs.length} verb pairs; ${entries.length} questions; ${entries.filter(q=>q.kind==='ji').length} jidoushi and ${entries.filter(q=>q.kind==='ta').length} tadoushi.`);
