"""Validate editorial questions against the pinned vocabulary and export the bank.

Uses the OpenJLPT cache populated by import_catalog.py. No source sentences
are copied: all context, Indonesian explanations and distractors are editorial.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(path):
    return json.loads(path.read_text(encoding='utf-8'))


def main():
    lock = load(ROOT / 'data/source-lock.json')
    vocab = [v for n in range(5, 0, -1) for v in load(ROOT / f'.cache/openjlpt/data_json_vocab_n{n}.json')]
    rows = load(ROOT / 'data/similar-quiz-editorial.json')
    questions, sources = [], []
    for row in rows:
        word, reading, target, meaning, writing_wrong, reading_wrong, sentence, translation, visual_note, reading_note = row
        candidates = [v for v in vocab if v['word'] == word and v['reading'] == reading]
        if not candidates:
            raise ValueError(f'No pinned source for {word} / {reading}')
        original = candidates[0]
        readings = sorted({v['reading'] for v in vocab if v['word'] == word})
        spellings = sorted({v['word'] for v in vocab if v.get('jmdict_id') == original['jmdict_id'] and v['reading'] == reading})
        if set(reading_wrong) & set(readings):
            raise ValueError(f'Accepted reading offered as incorrect: {word}')
        if set(writing_wrong) & set(spellings):
            raise ValueError(f'Accepted spelling offered as incorrect: {word}')
        if word.count(target) != 1 or sentence.count('{target}') != 1:
            raise ValueError(f'Question must have one target: {word}')
        for answer, wrong in [(word, writing_wrong), (reading, reading_wrong)]:
            if len(wrong) != 3 or len(set([answer, *wrong])) != 4:
                raise ValueError(f'Question must have four unique options: {word}')
        questions.append(dict(word=word, reading=reading, target=target,
                              level=original['level'], meaning=meaning,
                              writingDistractors=writing_wrong, readingDistractors=reading_wrong,
                              sentence=sentence, sentenceMeaning=translation,
                              visualExplanation=visual_note, readingExplanation=reading_note))
        sources.append(dict(word=word, reading=reading, level=original['level'],
                            sourceId=original['id'], jmdictId=original['jmdict_id'],
                            readings=readings, spellings=spellings, meaningsEn=original['meanings']))
    if len({q['word'] for q in questions}) != len(questions):
        raise ValueError('Duplicate vocabulary')
    (ROOT / 'similar-quiz-data.js').write_text(
        '// Generated by scripts/build_similar_quiz.py; edit data/similar-quiz-editorial.json.\n'
        '// Vocabulary: pinned OpenJLPT/JMdict. Original contexts and explanations.\n'
        '// CC BY-SA 4.0; see DATA-SOURCES.md.\n'
        'export const SIMILAR_VOCABULARY = ' + json.dumps(questions, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    (ROOT / 'data/similar-quiz-source.json').write_text(json.dumps(dict(
        source=lock['repository'], commit=lock['commit'], date='2026-10-13', words=sources,
        note='Vocabulary metadata only. All sentences, translations and distractors are original.'
    ), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'{len(questions)} vocabulary items; two directions per item.')
    print({f'N{n}':sum(q['level'] == f'N{n}' for q in questions) for n in range(5, 0, -1)})


if __name__ == '__main__':
    main()
