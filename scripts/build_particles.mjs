import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {PARTICLE_TOPICS,PARTICLE_EXAMPLES} from '../data/particle-source.mjs';

export function parseParticleSentence(raw) {
  let text='',before='',answer='',after='',cursor=0,start=-1,end=-1;const furigana=[];
  const tokens=/\[([^\[\]|]+)\|([^\[\]|]+)\]|\{\{([^{}]+)\}\}/gu;
  for(const match of raw.matchAll(tokens)) {
    text+=raw.slice(cursor,match.index);
    if(match[3]){assert.equal(start,-1,'One answer span per sentence');start=text.length;answer=match[3];text+=answer;end=text.length;}
    else {furigana.push([text.length,match[1],match[2]]);text+=match[1];}
    cursor=match.index+match[0].length;
  }
  text+=raw.slice(cursor);assert.ok(start>=0&&answer);assert.ok(!/[{}\[\]|]/u.test(text),'Malformed annotation');
  before=text.slice(0,start);after=text.slice(end);
  const uncovered=[...text].filter((char,i)=>/[\p{Script=Han}々]/u.test(char)&&!furigana.some(([offset,word])=>i>=offset&&i<offset+word.length));
  assert.equal(uncovered.length,0,`Missing furigana: ${text} ${uncovered}`);
  for(const [,word,reading] of furigana)assert.match(reading,/^[ぁ-ゖー]+$/u,word);
  return {before,answer,after,example:text,furigana};
}

const entries=PARTICLE_TOPICS.flatMap(topic=>PARTICLE_EXAMPLES[topic.id].map(([raw,translation,note,alternatives,options],i)=>{
  const sentence=parseParticleSentence(raw),accepted=[...new Set([topic.label,...(alternatives??topic.alternatives??[])])];
  assert.equal(sentence.answer,topic.label);assert.ok(translation&&note);
  const distractors=options??topic.distractors;
  assert.equal(distractors.length,3);assert.equal(new Set([topic.label,...distractors]).size,4);
  assert.ok(distractors.every(d=>!accepted.includes(d)),raw);
  return {id:`particle-${topic.id}-${String(i+1).padStart(2,'0')}`,topic:topic.id,...sentence,translation,note,accepted,distractors};
}));
assert.equal(new Set(entries.map(q=>q.example)).size,entries.length,'Duplicate sentence');
const output='// Generated by scripts/build_particles.mjs; original exercises and sources: DATA-SOURCES.md.\nexport const PARTICLE_TOPICS = '+JSON.stringify(PARTICLE_TOPICS.map(({alternatives,distractors,...topic})=>topic),null,2)+';\nexport const PARTICLE_ENTRIES = [\n'+entries.map(q=>'  '+JSON.stringify(q)).join(',\n')+'\n];\n';
writeFileSync(new URL('../particle-data.js',import.meta.url),output);
console.log(`${entries.length} particle questions across ${PARTICLE_TOPICS.length} topics; all kanji have reviewed furigana.`);
