"""Import the supplied N3 workbook read-only: python scripts/build_kotoba_n3.py file.xlsx."""
import hashlib
import json
import re
import sys
from collections import Counter
from pathlib import Path

from build_kotoba import ROOT, read_workbook


def build(path):
    rows = read_workbook(path)['Kotoba N3']
    assert [rows[0][1].get(c) for c in 'ABCDEF'] == [
        'Kotoba (Kana)', 'Kanji / Penulisan', 'Arti Indonesia (otomatis)',
        'Level', 'Jenis Kata', 'Arti Inggris (rujukan)']
    overrides = json.loads((ROOT/'data/kotoba-n3-overrides.json').read_text(encoding='utf-8'))
    entries, changes, used = [], [], set()
    for number, cells in rows[1:]:
        if not any(cells.values()):
            continue
        assert all(cells.get(c) for c in 'ACDEFHJ'), f'Missing data in row {number}'
        assert cells['D'] == 'N3'
        assert cells['J'] in ['Inti (JMdict)', 'Tambahan (periksa)']
        meaning = cells['C']
        # English infinitive "to" is not Indonesian purpose "untuk".
        if cells['E'].startswith('Kata kerja') and cells['F'].startswith('to '):
            meaning = re.sub(r'(^|[;,]\s*)untuk\s+', r'\1', meaning, flags=re.I)
        meaning = meaning.strip(' ;,')
        override = overrides.get(cells.get('B') or cells['A'])
        if override:
            assert cells['A'] == override['reading']
            meaning = override['meaning']
            used.add(cells.get('B') or cells['A'])
        if meaning != cells['C']:
            changes.append(dict(sourceRow=number, original=cells['C'], meaning=meaning))
        entries.append(dict(id=f'n3-row-{number}', sourceRow=number, level='N3',
                            reading=cells['A'], spelling=cells.get('B', ''), meaning=meaning,
                            meaningEn=cells['F'], type=cells['E'].lower(),
                            source=cells['H'], sourceGroup='core' if cells['J']=='Inti (JMdict)' else 'extra'))
    assert used == set(overrides), 'Unused editorial correction'
    assert len({(e['spelling'] or e['reading'], e['reading']) for e in entries}) == len(entries)
    manifest = dict(filename=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                    sheet='Kotoba N3', range=f'A2:J{entries[-1]["sourceRow"]}',
                    entryCount=len(entries), types=dict(Counter(e['type'] for e in entries)),
                    sourceGroups=dict(Counter(e['sourceGroup'] for e in entries)),
                    changes=changes, note='Arti Indonesia dari terjemahan otomatis workbook dengan koreksi terbatas; belum ditinjau seluruhnya. Status hafalan pribadi tidak diimpor.')
    output = '// Generated by scripts/build_kotoba_n3.py from the supplied workbook.\n'
    output += '// Attribution and share-alike terms: see DATA-SOURCES.md.\n'
    output += 'export const KOTOBA_N3_ENTRIES = [\n'
    output += ',\n'.join('  '+json.dumps(e, ensure_ascii=False) for e in entries)+'\n];\n'
    (ROOT/'kotoba-n3-data.js').write_text(output, encoding='utf-8')
    (ROOT/'data/kotoba-n3-source.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(f'{len(entries)} N3 entries; {len(changes)} translation edits; {len(overrides)} editorial corrections')


if __name__ == '__main__':
    build(Path(sys.argv[1]))
