"""Extract complete visible components for the local catalog from pinned KanjiVG.

Only component labels are exported, not stroke drawings. Run with --download
to fetch the pinned source; otherwise uses the local cache, without network.
KanjiVG © 2009–2026 Ulrich Apel, CC BY-SA 3.0. See DATA-SOURCES.md.
"""
from pathlib import Path
import argparse
import gzip
import hashlib
import json
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
VERSION = '20260714'
URL = f'https://github.com/KanjiVG/kanjivg/releases/download/r{VERSION}/kanjivg-{VERSION}.xml.gz'
FORMS = ['水', '氵', '氺', '辶', '⻌', '木', '手', '扌', '心', '忄', '⺗', '言', '糸', '艹', '人', '亻', '金', '門']
# The gate family explicitly includes complete nested 門, e.g. 簡 and 潤.
# Other families keep their existing main-component scope.
NESTED_FORMS = {'門'}
NS = '{http://kanjivg.tagaini.net}'


def visible_components(main):
    elements = {g.get(NS + 'element') for g in [main, *main]
                if g.get(NS + 'partial') != 'true'
                and (g.get(NS + 'element') not in NESTED_FORMS
                     or g.get(NS + 'part') is None)}
    elements.update(g.get(NS + 'element') for g in main.iter('g')
                    if g.get(NS + 'element') in NESTED_FORMS
                    and g.get(NS + 'partial') != 'true'
                    and g.get(NS + 'part') is None)
    return elements


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--download', action='store_true')
    args = parser.parse_args()
    path = ROOT / '.cache' / f'kanjivg-{VERSION}.xml.gz'
    if args.download and not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        request = urllib.request.Request(URL, headers={'User-Agent': 'NihongoBenkyo/2.0'})
        with urllib.request.urlopen(request, timeout=60) as response:
            path.write_bytes(response.read())
    raw = path.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    manifest_path = ROOT / 'data' / 'radical-source.json'
    if manifest_path.exists():
        previous = json.loads(manifest_path.read_text(encoding='utf-8'))
        if previous['version'] == VERSION and previous['sha256'] != digest:
            raise ValueError('Pinned KanjiVG archive changed; review source before updating.')
    entries = {k.attrib['id']: k for k in ET.fromstring(gzip.decompress(raw))}
    catalog = json.loads((ROOT / 'data' / 'catalog-source.json').read_text(encoding='utf-8'))
    members = {form: [] for form in FORMS}
    missing = []
    for card in catalog:
        char = card['char']
        entry = entries.get(f'kvg:kanji_{ord(char):05x}')
        if entry is None:
            missing.append(char)
            continue
        # Search deeper only for explicitly declared whole-shape families.
        elements = visible_components(entry[0])
        for form in FORMS:
            if form in elements:
                members[form].append(char)
    output = {form: ''.join(chars) for form, chars in members.items()}
    (ROOT / 'radical-members.js').write_text(
        '// Generated by scripts/build_radicals.py from KanjiVG r20260714.\n'
        '// © 2009–2026 Ulrich Apel; component data licensed CC BY-SA 3.0.\n'
        '// See data/licenses/KanjiVG-NOTICE.md. Do not edit by hand.\n'
        'export const RADICAL_MEMBERS = ' + json.dumps(output, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    manifest = dict(repository='https://github.com/KanjiVG/kanjivg', version=VERSION,
                    url=URL, sha256=digest, retrieved='2026-10-13',
                    extracted='2026-10-14', nestedForms=sorted(NESTED_FORMS),
                    catalogCount=len(catalog), missing=missing,
                    counts={form: len(chars) for form, chars in members.items()})
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(manifest, ensure_ascii=True, indent=2))


if __name__ == '__main__':
    main()
