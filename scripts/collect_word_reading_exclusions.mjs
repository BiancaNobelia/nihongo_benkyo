// Refresh the exact-spelling JMdict exclusions for the per-word quiz.
// Downloads are cached; runtime quizzes require no network access.
import {readFileSync,writeFileSync,readdirSync,existsSync,mkdirSync} from 'node:fs';
import {KANJI} from '../kanji-data.js';

const root=new URL('../',import.meta.url);
const accepted=new Map();
const provenance=new Map();
for(const k of KANJI)if(k.example){
  const e=k.example;
  if(!accepted.has(e.word))accepted.set(e.word,new Set());
  for(const value of [e.reading,...e.readings])accepted.get(e.word).add(value);
}
const cached=new Set();
const han=word=>[...word].filter(c=>/\p{Unified_Ideograph}/u.test(c));
function addEntries(entries,char){
  for(const entry of entries)for(const v of entry.variants||[]){
    if(accepted.has(v.written)&&/^[ぁ-ゖーァ-ヶ]+$/u.test(v.pronounced)){
      accepted.get(v.written).add(v.pronounced.replace(/[ァ-ヶ]/gu,c=>String.fromCodePoint(c.codePointAt(0)-0x60)));
      if(!provenance.has(v.written))provenance.set(v.written,char);
    }
  }
}
for(const dir of ['.cache/words/','.cache/review-dictionary/','.cache/reading-dictionary/']){
  const directory=new URL(dir,root);
  if(!existsSync(directory))continue;
  for(const file of readdirSync(directory).filter(f=>/^[0-9a-f]+\.json$/.test(f))){
    const char=String.fromCodePoint(parseInt(file,16));
    addEntries(JSON.parse(readFileSync(new URL(file,directory))),char);
    cached.add(char);
  }
}
let uncovered=[...accepted.keys()].filter(word=>!han(word).some(c=>cached.has(c)));
const fetchChars=[];
while(uncovered.length){
  const counts=new Map();
  for(const word of uncovered)for(const char of new Set(han(word)))counts.set(char,(counts.get(char)||0)+1);
  const char=[...counts].sort((a,b)=>b[1]-a[1])[0]?.[0];
  if(!char)throw Error(`No kanji index for ${uncovered.join(', ')}`);
  fetchChars.push(char);uncovered=uncovered.filter(w=>!w.includes(char));
}
console.log(`Checking ${accepted.size} words; fetching ${fetchChars.length} missing dictionary indexes.`);
mkdirSync(new URL('.cache/reading-dictionary/',root),{recursive:true});
let next=0,done=0;
await Promise.all(Array.from({length:4},async()=>{
  while(next<fetchChars.length){
    const char=fetchChars[next++];let entries;
    for(let attempt=0;attempt<3;attempt++){
      try{
        const response=await fetch(`https://kanjiapi.dev/v1/words/${encodeURIComponent(char)}`,{signal:AbortSignal.timeout(30000)});
        if(response.status===404){entries=[];break;}
        if(!response.ok)throw Error(`HTTP ${response.status}`);
        entries=await response.json();break;
      }catch(error){if(attempt===2)throw error;}
    }
    writeFileSync(new URL(`.cache/reading-dictionary/${char.codePointAt(0).toString(16)}.json`,root),JSON.stringify(entries));
    addEntries(entries,char);cached.add(char);
    if(++done%25===0||done===fetchChars.length)console.log(`${done}/${fetchChars.length} indexes saved.`);
  }
}));
const words=[...accepted].map(([word,values])=>({word,readings:[...values].sort(),
  dictionaryUrl:`https://kanjiapi.dev/v1/words/${encodeURIComponent(provenance.get(word)||han(word).find(c=>cached.has(c)))}`,
  exactMatch:provenance.has(word),
}));
const source={date:new Date().toISOString().slice(0,10),source:'JMdict via kanjiapi.dev, plus the pinned catalog readings',words};
writeFileSync(new URL('data/word-reading-exclusions.json',root),JSON.stringify(source,null,2)+'\n');
writeFileSync(new URL('word-reading-exclusions.js',root),
  '// Generated by scripts/collect_word_reading_exclusions.mjs. JMdict, CC BY-SA 4.0; see DATA-SOURCES.md.\n'+
  'export const WORD_READING_EXCLUSIONS = '+JSON.stringify(Object.fromEntries(words.map(q=>[q.word,q.readings])))+';\n');
console.log(JSON.stringify({words:words.length,exactMatches:words.filter(q=>q.exactMatch).length,withoutExactMatch:words.filter(q=>!q.exactMatch).map(q=>q.word)}));
