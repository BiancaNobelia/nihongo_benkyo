import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {conjugateVerb,henkanOptions,HENKAN_LEVELS,VERB_GROUPS,FORM_LABELS} from '../henkan-core.js';
const read=name=>JSON.parse(readFileSync(new URL(`../data/${name}`,import.meta.url),'utf8'));
const verbs=read('henkan-verbs.json'),source=read('henkan-source.json');
assert.equal(verbs.length,source.entryCount);
assert.equal(new Set(verbs.map(v=>v.id)).size,verbs.length);
assert.equal(new Set(verbs.map(v=>`${v.word}|${v.reading}`)).size,verbs.length);
for(const v of verbs) {
  assert.ok(HENKAN_LEVELS.includes(v.level)&&VERB_GROUPS[v.group]&&v.meaning&&v.sources.length,v.word);
  assert.match(v.reading,/^[ぁ-ゖー]+$/u,v.word);
  const f=conjugateVerb(v);
  for(const form of Object.keys(FORM_LABELS)) {
    if(!f[form])continue;
    const options=henkanOptions(v,form,()=>0.5);
    assert.equal(new Set(options).size,4,`${v.word} ${form}`);
    for(const answer of options)assert.match(answer,/^[ぁ-ゖー]+$/u,v.word);
  }
}
const out='// Generated by scripts/build_henkan.mjs; sources and attribution: DATA-SOURCES.md.\nexport const HENKAN_VERBS = [\n'+verbs.map(v=>'  '+JSON.stringify(v)).join(',\n')+'\n];\n';
writeFileSync(new URL('../henkan-data.js',import.meta.url),out);
console.log(`${verbs.length} verbs: ${HENKAN_LEVELS.map(l=>`${l} ${verbs.filter(v=>v.level===l).length}`).join(', ')}`);
