"""Extract the user-provided practice workbook without modifying it.

Usage: python scripts/build_kotoba.py /path/to/workbook.xlsx
Uses only the Python standard library; retains every source row and chapter.
"""
import hashlib
import json
import re
import sys
from collections import Counter
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
NS = {'s': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}


def read_workbook(path):
    sheets = {}
    with ZipFile(path) as archive:
        strings = []
        if 'xl/sharedStrings.xml' in archive.namelist():
            strings = [''.join(t.text or '' for t in si.findall('.//s:t', NS))
                       for si in ET.fromstring(archive.read('xl/sharedStrings.xml'))]
        relations = {r.attrib['Id']: r.attrib['Target'] for r in
                     ET.fromstring(archive.read('xl/_rels/workbook.xml.rels'))}
        workbook = ET.fromstring(archive.read('xl/workbook.xml'))
        for sheet in workbook.find('s:sheets', NS):
            target = relations[sheet.attrib['{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id']]
            target = target.lstrip('/') if target.startswith('/') else 'xl/' + target
            rows = []
            for row in ET.fromstring(archive.read(target)).findall('s:sheetData/s:row', NS):
                cells = {}
                for cell in row:
                    value = cell.find('s:v', NS)
                    kind = cell.attrib.get('t')
                    if kind == 'inlineStr':
                        value = ''.join(t.text or '' for t in cell.findall('.//s:t', NS))
                    elif kind == 's':
                        value = strings[int(value.text)]
                    else:
                        value = value.text if value is not None else ''
                    cells[re.sub(r'\d+', '', cell.attrib['r'])] = value.strip()
                rows.append((int(row.attrib['r']), cells))
            sheets[sheet.attrib['name']] = rows
    return sheets


def build(path):
    sheets = read_workbook(path)
    source_sheet = 'Kotoba Bab 1-50'
    assert list(sheets[source_sheet][0][1].values()) == ['Kotoba', 'Kanji', 'Arti', 'Bab', 'Jenis Kata']
    entries = []
    for row, cells in sheets[source_sheet][1:]:
        if not any(cells.values()):
            continue
        assert all(cells.get(c) for c in 'ACDE'), f'Missing required cell in row {row}'
        chapter = int(cells['D'])
        assert 1 <= chapter <= 50
        entries.append(dict(id=f'minna-row-{row}', sourceRow=row, chapter=chapter,
                            reading=cells['A'], spelling=cells.get('B', ''),
                            meaning=cells['C'], type=cells['E']))
    counts = Counter(e['chapter'] for e in entries)
    chapters = []
    for _, cells in sheets['Ringkasan'][1:]:
        if not cells.get('A', '').isdigit():
            continue
        n = int(cells['A'])
        assert counts[n] == int(cells['B']), f'Chapter {n} count does not match summary'
        chapters.append(dict(number=n, count=counts[n], title=cells['C']))
    assert [c['number'] for c in chapters] == list(range(1, 51))
    note = 'Kompilasi latihan Bab 1–50 dari file pengguna yang mengikuti topik Minna no Nihongo I & II; bukan daftar resmi lengkap buku.'
    manifest = dict(filename=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                    sheet=source_sheet, range=f'A2:E{entries[-1]["sourceRow"]}',
                    entryCount=len(entries), book1Count=sum(counts[n] for n in range(1,26)),
                    book2Count=sum(counts[n] for n in range(26,51)), note=note,
                    types=dict(Counter(e['type'] for e in entries)), chapters=chapters)
    output = '// Generated by scripts/build_kotoba.py from the supplied workbook.\n'
    output += 'export const KOTOBA_CHAPTERS = ' + json.dumps(chapters, ensure_ascii=False, indent=2) + ';\n'
    output += 'export const KOTOBA_ENTRIES = [\n'
    output += ',\n'.join('  ' + json.dumps(e, ensure_ascii=False) for e in entries) + '\n];\n'
    (ROOT/'kotoba-data.js').write_text(output, encoding='utf-8')
    (ROOT/'data/kotoba-source.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(f'{len(entries)} entries, {len(chapters)} chapters; I: {manifest["book1Count"]}, II: {manifest["book2Count"]}')


if __name__ == '__main__':
    build(Path(sys.argv[1]))
