import {writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {KOTOBA_ENTRIES} from '../kotoba-data.js';
import {KOTOBA_N3_ENTRIES} from '../kotoba-n3-data.js';

const excludedWords={
  'お名前は？':'Kalimat tanya, bukan kata benda dasar.',
  'から':'Partikel.', 'まで':'Partikel.', 'だけ':'Partikel.', 'ぐらい':'Partikel.',
  '歩いて':'Kata kerja yang sudah berubah ke bentuk て.',
  '一人で':'Frasa keterangan yang sudah memakai で.', '一緒に':'Frasa keterangan yang sudah memakai に.',
  'ちょっと':'Keterangan.', 'いろいろ':'Latih sebagai kata sifat/keterangan, bukan noun dalam bank ini.',
  'ぜひ':'Keterangan.', 'もちろん':'Keterangan.', 'じゃあ':'Penghubung percakapan.',
  'どうしたの':'Kalimat tanya.', 'いいよ':'Ungkapan dengan kata sifat.', 'そうかな':'Ungkapan percakapan.',
  '何月':'Kata tanya yang memerlukan konteks.', '何日':'Kata tanya yang memerlukan konteks.', '何人':'Kata tanya yang memerlukan konteks.',
  '国際':'Umumnya bagian gabungan kata, bukan predikat nominal mandiri dalam latihan ini.',
  'はず':'Nomina terikat yang memerlukan pelengkap.', '気味':'Memerlukan pelengkap atau konteks khusus.',
  '具体':'Umumnya memakai ～的 atau gabungan kata.', '際':'Nomina yang memerlukan konteks/pelengkap.',
  '次第':'Pola dan maknanya memerlukan konteks.', '週間':'Satuan durasi yang memerlukan bilangan.',
  'いらいら':'Bentuk keterangan/する, bukan noun predikatif dalam latihan ini.',
  'で':'Entri ambigu; jangan mengubah partikel menjadi predikat.', 'ね':'Entri ambigu; jangan mengubah partikel menjadi predikat.',
  'どうか':'Keterangan/ungkapan permintaan.', 'ただ':'Keterangan atau sifat tanpa biaya; memerlukan pemilihan makna.',
  'たとえ':'Entri ambigu antara keterangan dan nomina contoh/perumpamaan.',
  'せい':'Nomina terikat yang memerlukan pelengkap.', '軒':'Sufiks penggolong yang memerlukan bilangan.',
  '様':'Makna dan bacaan memerlukan konteks, termasuk sufiks sapaan.',
};
const toHiragana=s=>s.normalize('NFKC').replace(/[ァ-ヶ]/g,c=>String.fromCharCode(c.charCodeAt(0)-0x60));
const rows=[...KOTOBA_ENTRIES,...KOTOBA_N3_ENTRIES].filter(e=>e.type.includes('kata benda'));
const nouns=new Map(),excluded=[];
for(const e of rows){
  const word=e.spelling||e.reading,reading=toHiragana(e.reading),level=e.chapter?(e.chapter<=25?'N5':'N4'):'N3';
  const reason=excludedWords[word]||(!/^[ぁ-ゖー]+$/u.test(reading)?'Bacaan memuat anotasi, simbol, atau beberapa alternatif.':!e.meaning?'Arti belum tersedia.':null);
  if(reason){excluded.push({id:e.id,word,reason});continue;}
  const key=word+'|'+reading;
  if(nouns.has(key)){
    const n=nouns.get(key);n.sources.push(e.id);
    if(['N5','N4','N3'].indexOf(level)<['N5','N4','N3'].indexOf(n.level))n.level=level;
    continue;
  }
  nouns.set(key,{id:`noun-${e.id}`,word,reading,meaning:e.meaning,level,group:'noun',sources:[e.id]});
}
const data=[...nouns.values()];
assert.ok(data.length>1000);
assert.equal(new Set([...data.flatMap(n=>n.sources),...excluded.map(e=>e.id)]).size,rows.length);
const meta={entryCount:data.length,sourceRows:rows.length,levels:Object.fromEntries(['N5','N4','N3'].map(l=>[l,data.filter(n=>n.level===l).length])),coveredSourceIds:data.flatMap(n=>n.sources).sort(),excluded};
writeFileSync(new URL('../henkan-noun-data.js',import.meta.url),'// Generated by scripts/build_henkan_nouns.mjs. Attribution: DATA-SOURCES.md.\nexport const HENKAN_NOUNS = [\n'+data.map(n=>'  '+JSON.stringify(n)).join(',\n')+'\n];\n');
writeFileSync(new URL('../data/henkan-noun-source.json',import.meta.url),JSON.stringify(meta,null,2)+'\n');
console.log(JSON.stringify({nouns:data.length,questions:data.length*4,levels:meta.levels,excluded:excluded.length}));
