"""Select complete visual anchors without claiming a full decomposition.

Unnamed strokes, partial components and split components are never invented.
Positions are deliberately omitted: nested groups may have relative positions.
"""
import gzip
import hashlib
import json
import xml.etree.ElementTree as ET
from pathlib import Path
from build_components import BASIC, FORMS, NS

ROOT = Path(__file__).resolve().parents[1]


def anchors(node, char, meanings):
    symbol = node.get(NS + 'element')
    original = node.get(NS + 'original', symbol)
    if node.get(NS + 'partial') == 'true' or node.get(NS + 'part'):
        return []
    if symbol and symbol != char:
        if symbol == '月' and original == '肉':
            return [{'symbol': symbol, 'meaning': 'daging; tubuh'}]
        if symbol in FORMS:
            return [{'symbol': symbol, 'meaning': FORMS[symbol][1]}]
        if original == symbol and symbol in meanings:
            return [{'symbol': symbol, 'meaning': meanings[symbol]}]
    result = []
    for child in node:
        if child.tag == 'g':
            result.extend(anchors(child, char, meanings))
    return result


def main():
    manifest = json.loads((ROOT / 'data/radical-source.json').read_text(encoding='utf8'))
    raw = (ROOT / '.cache' / f'kanjivg-{manifest["version"]}.xml.gz').read_bytes()
    assert hashlib.sha256(raw).hexdigest() == manifest['sha256']
    entries = {k.attrib['id']: k[0] for k in ET.fromstring(gzip.decompress(raw))}
    reviewed = json.loads((ROOT / 'data/reviewed-id.json').read_text(encoding='utf8'))['entries']
    meanings = {c: e['meaning'] for c, e in reviewed.items()}
    result = {}
    for char in meanings:
        node = entries.get(f'kvg:kanji_{ord(char):05x}')
        if node is None or char in BASIC:
            continue
        parts = anchors(node, char, meanings)
        if parts:
            # Keep at most two recognizable anchors, not a wall of components.
            seen = set()
            result[char] = [part for part in parts if not (part['symbol'] in seen or seen.add(part['symbol']))][:2]
    (ROOT / 'kanji-memory-anchors.js').write_text(
        '// Generated by scripts/build_memory_anchors.py from KanjiVG r20260714.\n'
        '// © Ulrich Apel and contributors, CC BY-SA 3.0; Indonesian glosses adapted.\n'
        '// Complete visual anchors only; not a full decomposition or etymology.\n'
        'export const MEMORY_ANCHORS = ' + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf8')
    print(f'{len(result)} characters with complete visual anchors')


if __name__ == '__main__':
    main()
