// Offline build of reviewed adaptations of the user-supplied N4 PDF exercises.
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url);
const questions=[];
const categories=new Set(['noun','verb','adjective','adverb','special']);
for(let test=1;test<=10;test++){
  const rows=JSON.parse(readFileSync(new URL(`data/n4-pdf-${String(test).padStart(2,'0')}.json`,root)));
  assert.equal(rows.length,20);
  for(const [index,row] of rows.entries()){
    const [number,word,reading,meaning,sentence,sentenceMeaning,distractors,readingCategory]=row;
    assert.equal(number,index+1);
    assert.equal(sentence.split('{target}').length,2);
    assert.match(word,/\p{Script=Han}/u);
    assert.equal(distractors.length,3);
    assert.equal(new Set([reading,...distractors]).size,4);
    for(const value of [reading,...distractors])assert.match(value,/^[ぁ-ゖー]+$/u);
    assert.ok(meaning && sentenceMeaning);
    assert.ok(categories.has(readingCategory));
    questions.push({id:`n4-pdf-${test}-${number}`,contextKey:`pdf-n4-${test}-${number}`,
      level:'N4',levelBasis:'n4-minna-2-reviewed',word,reading,meaning,sentence,sentenceMeaning,distractors,readingCategory,
      explanation:`Dalam kalimat ini, ${word} dibaca ${reading}.`,
      source:{file:`N4_${test}.pdf`,question:number},
    });
  }
}
assert.equal(new Set(questions.map(q=>`${q.word}:${q.reading}:${q.sentence}`)).size,questions.length);
writeFileSync(new URL('n4-reading-data.js',root),
  '// Generated by scripts/build_n4_reading.mjs. Reviewed PDF adaptations; see DATA-SOURCES.md.\n'+
  'export const N4_PDF_READINGS = [\n'+questions.map(q=>'  '+JSON.stringify(q)).join(',\n')+'\n];\n');
console.log(`Built ${questions.length} N4 sentence exercises.`);
