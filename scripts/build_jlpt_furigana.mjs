// Reviewed readings for the existing JLPT bank. No automatic on/kun guessing.
// Run after changing a sentence; unknown context words deliberately fail the build.
import {readFileSync, writeFileSync} from 'node:fs';
import {getQuizPool} from '../practice-banks.js';

const lexicon=JSON.parse(readFileSync(new URL('../data/jlpt-furigana-readings.json',import.meta.url),'utf8'));
const hira=text=>text.replace(/[ァ-ヶ]/g,char=>String.fromCharCode(char.charCodeAt(0)-0x60));
const regexEscape=text=>text.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');

function contextReading(word,before,after) {
  switch(word){
    case '来': return /^る/.test(after)?'く':/^な/.test(after)?'こ':'き';
    case '間': return /^に合/.test(after)?'ま':'あいだ';
    case '下': return /^り/.test(after)?'お':'した';
    case '少': return /^な/.test(after)?'すく':'すこ';
    case '足': return /^り/.test(after)?'た':'あし';
    case '降': return /^り/.test(after)?'お':'ふ';
    case '月': return /[ヶか]$/.test(before)?'げつ':'つき';
    case '開': return /^かれ/.test(after)?'ひら':'あ';
    case '出': return /思い$/.test(before)||/^して/.test(after)?'だ':'で';
    case '母': return /お$/.test(before)?'かあ':'はは';
    case '姉': return /お$/.test(before)?'ねえ':'あね';
    case '話': return /^さ/.test(after)?'はな':'はなし';
    case '入': return /^り口/.test(after)?'い':'はい';
    case '急': return /^に/.test(after)?'きゅう':'いそ';
    case '後': return /^ろ/.test(after)?'うし':'あと';
    case '空': return /^いて/.test(after)?'あ':'そら';
    case '兄': return /お$/.test(before)?'にい':'あに';
    case '通': return /^り/.test(after)?'とお':'かよ';
    default: return lexicon[word];
  }
}

function surroundings(text,fullText,offset) {
  const spans=[];
  for(const match of text.matchAll(/[0-9０-９]*[\p{Script=Han}々]+(?:ヶ[\p{Script=Han}々]+)?/gu)){
    const [word]=match;
    const start=offset+match.index;
    const reading=contextReading(word,fullText.slice(0,start),fullText.slice(start+word.length));
    if(!reading)throw new Error(`Missing reading: ${word} in ${fullText}`);
    const parts=typeof reading==='string'?[[word,reading]]:reading;
    if(parts.map(part=>part[0]).join('')!==word)throw new Error(`Invalid word split: ${word}`);
    let position=match.index;
    for(const [base,kana] of parts){spans.push([position,base,kana]);position+=base.length;}
  }
  return spans;
}

function targetSpans(word,reading) {
  // Kana anchors keep okurigana outside ruby; irregular compounds and numeric
  // counters use the exact answer already reviewed in the question bank.
  const parts=word.split(/([\p{Script=Han}々0-9０-９]+)/u);
  const pattern=parts.map((part,i)=>i%2?'(.+?)':regexEscape(hira(part))).join('');
  const match=hira(reading).match(new RegExp(`^${pattern}$`,'u'));
  if(!match)throw new Error(`Cannot align target: ${word} / ${reading}`);
  let position=0,capture=1;
  return parts.flatMap((part,i)=>{
    const span=i%2?[[position,part,match[capture++]]]:[];
    position+=part.length;return span;
  });
}

const records=getQuizPool('jlpt-reading').map(q=>{
  const [before,after]=q.sentence.split('{target}');
  const fullText=before+q.word+after;
  return [JSON.stringify([q.sentence,q.word,q.reading]),[
    surroundings(before,fullText,0),targetSpans(q.word,q.reading),
    surroundings(after,fullText,before.length+q.word.length),
  ]];
});
const output='// Generated by scripts/build_jlpt_furigana.mjs. Exact sentence/word/answer keys prevent stale readings.\n'+
  'export const JLPT_FURIGANA = new Map([\n'+records.map(row=>JSON.stringify(row)).join(',\n')+'\n]);\n';
writeFileSync(new URL('../jlpt-furigana-data.js',import.meta.url),output);
console.log(`Annotated ${records.length} JLPT questions.`);
