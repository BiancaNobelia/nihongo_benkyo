// Offline build of reviewed adaptations of the user-supplied N5 PDF exercises.
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url);
const questions=[];
for(let test=1;test<=10;test++){
  const rows=JSON.parse(readFileSync(new URL(`data/n5-pdf-${String(test).padStart(2,'0')}.json`,root)));
  assert.equal(rows.length,test===10 ? 19 : 20);
  for(const [index,row] of rows.entries()){
    const [number,word,reading,meaning,sentence,sentenceMeaning,distractors,readingCategory]=row;
    assert.equal(number,index+1);
    assert.equal(sentence.split('{target}').length,2);
    assert.match(word,/\p{Script=Han}/u);
    assert.equal(new Set([reading,...distractors]).size,4);
    for(const value of [reading,...distractors])assert.match(value,/^[ぁ-ゖー]+$/u);
    assert.ok(meaning && sentenceMeaning);
    questions.push({id:`n5-pdf-${test}-${number}`,contextKey:`pdf-n5-${test}-${number}`,
      level:'N5',levelBasis:'n5-minna-1-reviewed',word,reading,meaning,sentence,sentenceMeaning,distractors,readingCategory,
      explanation:`Dalam kalimat ini, ${word} dibaca ${reading}.`,
      source:{file:`N5_${test}.pdf`,question:number},
    });
  }
}
const overrides=JSON.parse(readFileSync(new URL('data/n5-context-overrides.json',root)));
writeFileSync(new URL('n5-reading-data.js',root),
  '// Generated by scripts/build_n5_reading.mjs. Reviewed PDF adaptations; see DATA-SOURCES.md.\n'+
  'export const N5_PDF_READINGS = [\n'+questions.map(q=>'  '+JSON.stringify(q)).join(',\n')+'\n];\n'+
  'export const N5_CONTEXT_OVERRIDES = '+JSON.stringify(overrides,null,2)+';\n');
console.log(`Built ${questions.length} N5 sentence exercises and ${Object.keys(overrides).length} simpler contexts.`);
