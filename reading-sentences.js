export const READING_SENTENCES = new Map(SENTENCES.map(([word,sentence,sentenceMeaning])=>[word,{sentence,sentenceMeaning}]));
const existingContexts=new Map([...SIMILAR_VOCABULARY,...SPECIAL_READINGS]
  .filter(q=>q.sentence && q.sentenceMeaning)
  .map(q=>[readingQuestionKey(q),{sentence:q.sentence,sentenceMeaning:q.sentenceMeaning}]));

export function withReadingSentence(question) {
  if(question.sentence && question.sentenceMeaning)return question;
  const context=existingContexts.get(readingQuestionKey(question)) || READING_SENTENCES.get(question.word);
  if(!context)throw new Error(`Missing JLPT sentence: ${question.word}`);
  return {...question,...context};
}
